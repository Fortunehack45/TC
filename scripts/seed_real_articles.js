async function seed() {
  console.log('Seeding authentic real news articles into Supabase tc_articles table...');
  let successCount = 0;

  for (const article of REAL_ARTICLES) {
    const { error } = await supabase
      .from('tc_articles')
      .upsert(article, { onConflict: 'id' });

    if (error) {
      console.error(`Failed to upsert article ${article.slug}:`, error.message);
    } else {
      successCount++;
    }
  }

  console.log(`Successfully seeded ${successCount} of ${REAL_ARTICLES.length} authentic articles into Supabase!`);
}

seed().catch(console.error);
